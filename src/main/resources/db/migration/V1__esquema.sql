-- ---------------------------------------------------------
-- 1. CARRERAS
-- ---------------------------------------------------------
CREATE TABLE carrera (
    id_carrera BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL UNIQUE,
    activa BOOLEAN NOT NULL DEFAULT TRUE
);

-- ---------------------------------------------------------
-- 2. USUARIOS
-- ---------------------------------------------------------
CREATE TABLE usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    nombre VARCHAR(100) NOT NULL,
    apellidos VARCHAR(150) NOT NULL,

    correo_institucional VARCHAR(255) NOT NULL,
    correo_verificado BOOLEAN NOT NULL DEFAULT FALSE,

    password_hash VARCHAR(255) NOT NULL,

    tipo_usuario VARCHAR(15) NOT NULL
        CHECK (tipo_usuario IN ('ESTUDIANTE', 'EGRESADO')),

    matricula VARCHAR(30),
    anio_egreso INTEGER,

    id_carrera BIGINT NOT NULL
        REFERENCES carrera(id_carrera),

    telefono VARCHAR(25),
    foto_url TEXT,

    rol VARCHAR(10) NOT NULL DEFAULT 'USUARIO'
        CHECK (rol IN ('USUARIO', 'ADMIN')),

    activo BOOLEAN NOT NULL DEFAULT TRUE,

    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_usuario_matricula UNIQUE (matricula),

    CONSTRAINT chk_usuario_datos_academicos CHECK (
        (tipo_usuario = 'ESTUDIANTE'
            AND matricula IS NOT NULL
            AND anio_egreso IS NULL)
        OR
        (tipo_usuario = 'EGRESADO'
            AND anio_egreso IS NOT NULL
            AND anio_egreso > 0)
    )
);

-- Ignora diferencias entre mayúsculas y minúsculas
-- al comprobar que el correo no esté repetido.
CREATE UNIQUE INDEX uq_usuario_correo_lower
    ON usuario (LOWER(correo_institucional));

CREATE INDEX idx_usuario_carrera
    ON usuario (id_carrera);

CREATE INDEX idx_usuario_activo
    ON usuario (activo);

-- ---------------------------------------------------------
-- 3. CÓDIGOS DE VERIFICACIÓN
-- ---------------------------------------------------------
CREATE TABLE codigo_verificacion (
    id_codigo BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_usuario BIGINT NOT NULL
        REFERENCES usuario(id_usuario) ON DELETE CASCADE,

    codigo_hash VARCHAR(255) NOT NULL,

    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_expiracion TIMESTAMPTZ NOT NULL,

    fecha_uso TIMESTAMPTZ,

    intentos INTEGER NOT NULL DEFAULT 0
        CHECK (intentos >= 0),

    CONSTRAINT chk_codigo_fechas
        CHECK (fecha_expiracion > fecha_creacion)
);

CREATE INDEX idx_codigo_usuario_expiracion
    ON codigo_verificacion (id_usuario, fecha_expiracion);

-- ---------------------------------------------------------
-- 4. CATEGORÍAS Y SUBCATEGORÍAS
-- ---------------------------------------------------------
CREATE TABLE categoria (
    id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    nombre VARCHAR(100) NOT NULL UNIQUE,

    id_categoria_padre BIGINT
        REFERENCES categoria(id_categoria)
        ON DELETE RESTRICT,

    descripcion TEXT,
    activa BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT chk_categoria_no_autorreferencia
        CHECK (
            id_categoria_padre IS NULL
            OR id_categoria_padre <> id_categoria
        )
);

CREATE INDEX idx_categoria_padre
    ON categoria (id_categoria_padre);

-- ---------------------------------------------------------
-- 5. EMPRENDIMIENTOS
-- ---------------------------------------------------------
CREATE TABLE emprendimiento (
    id_emprendimiento BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_usuario BIGINT NOT NULL
        REFERENCES usuario(id_usuario)
        ON DELETE RESTRICT,

    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT,

    logo_url TEXT,
    horario VARCHAR(255),
    contacto VARCHAR(255),

    activo BOOLEAN NOT NULL DEFAULT TRUE,

    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_emprendimiento_usuario
    ON emprendimiento (id_usuario);

-- ---------------------------------------------------------
-- 6. PUBLICACIONES
-- ---------------------------------------------------------
CREATE TABLE publicacion (
    id_publicacion BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_usuario BIGINT NOT NULL
        REFERENCES usuario(id_usuario)
        ON DELETE RESTRICT,

    id_categoria BIGINT NOT NULL
        REFERENCES categoria(id_categoria)
        ON DELETE RESTRICT,

    id_emprendimiento BIGINT
        REFERENCES emprendimiento(id_emprendimiento)
        ON DELETE SET NULL,

    tipo VARCHAR(15) NOT NULL
        CHECK (tipo IN ('VENTA', 'INTERCAMBIO', 'DONACION')),

    titulo VARCHAR(180) NOT NULL,
    descripcion TEXT NOT NULL,

    precio NUMERIC(10,2) NOT NULL DEFAULT 0
        CHECK (precio >= 0),

    condicion VARCHAR(20)
        CHECK (
            condicion IN (
                'NUEVO',
                'COMO_NUEVO',
                'USADO',
                'DESGASTADO'
            )
        ),

    punto_entrega VARCHAR(255),

    estado VARCHAR(15) NOT NULL DEFAULT 'ACTIVA'
        CHECK (
            estado IN (
                'ACTIVA',
                'RESERVADA',
                'FINALIZADA',
                'PAUSADA',
                'ELIMINADA'
            )
        ),

    fecha_publicacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_publicacion_donacion CHECK (
        tipo <> 'DONACION' OR precio = 0
    ),

    CONSTRAINT chk_publicacion_condicion CHECK (
        condicion IS NOT NULL OR id_emprendimiento IS NOT NULL
    )
);

CREATE INDEX idx_publicacion_catalogo
    ON publicacion (estado, tipo, id_categoria);

CREATE INDEX idx_publicacion_usuario
    ON publicacion (id_usuario, fecha_publicacion DESC);

CREATE INDEX idx_publicacion_fecha
    ON publicacion (fecha_publicacion DESC);

CREATE INDEX idx_publicacion_emprendimiento
    ON publicacion (id_emprendimiento);

-- Búsqueda textual básica en título y descripción.
CREATE INDEX idx_publicacion_texto
    ON publicacion
    USING GIN (
        TO_TSVECTOR(
            'spanish',
            COALESCE(titulo, '') || ' ' || COALESCE(descripcion, '')
        )
    );

-- ---------------------------------------------------------
-- 7. IMÁGENES DE LAS PUBLICACIONES
-- ---------------------------------------------------------
CREATE TABLE imagen_publicacion (
    id_imagen BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_publicacion BIGINT NOT NULL
        REFERENCES publicacion(id_publicacion)
        ON DELETE CASCADE,

    url TEXT NOT NULL,
    orden SMALLINT NOT NULL DEFAULT 1
        CHECK (orden > 0),

    CONSTRAINT uq_imagen_orden
        UNIQUE (id_publicacion, orden)
);

-- ---------------------------------------------------------
-- 8. FAVORITOS
-- ---------------------------------------------------------
CREATE TABLE favorito (
    id_usuario BIGINT NOT NULL
        REFERENCES usuario(id_usuario)
        ON DELETE CASCADE,

    id_publicacion BIGINT NOT NULL
        REFERENCES publicacion(id_publicacion)
        ON DELETE CASCADE,

    fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (id_usuario, id_publicacion)
);

CREATE INDEX idx_favorito_publicacion
    ON favorito (id_publicacion);

-- ---------------------------------------------------------
-- 9. TRANSACCIONES ENTRE USUARIOS
-- No procesa pagos en línea de las compraventas.
-- Registra acuerdos, apartados y entregas.
-- ---------------------------------------------------------
CREATE TABLE transaccion (
    id_transaccion BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_publicacion BIGINT NOT NULL
        REFERENCES publicacion(id_publicacion)
        ON DELETE RESTRICT,

    id_comprador BIGINT NOT NULL
        REFERENCES usuario(id_usuario)
        ON DELETE RESTRICT,

    id_vendedor BIGINT NOT NULL
        REFERENCES usuario(id_usuario)
        ON DELETE RESTRICT,

    precio_acordado NUMERIC(10,2) NOT NULL DEFAULT 0
        CHECK (precio_acordado >= 0),

    estado VARCHAR(15) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (
            estado IN (
                'PENDIENTE',
                'ACEPTADA',
                'COMPLETADA',
                'CANCELADA'
            )
        ),

    fecha_solicitud TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_cierre TIMESTAMPTZ,

    CONSTRAINT chk_transaccion_participantes
        CHECK (id_comprador <> id_vendedor),

    CONSTRAINT chk_transaccion_cierre
        CHECK (
            estado <> 'COMPLETADA'
            OR fecha_cierre IS NOT NULL
        )
);

CREATE INDEX idx_transaccion_publicacion
    ON transaccion (id_publicacion);

CREATE INDEX idx_transaccion_comprador
    ON transaccion (id_comprador, estado);

CREATE INDEX idx_transaccion_vendedor
    ON transaccion (id_vendedor, estado);

-- ---------------------------------------------------------
-- 10. RESEÑAS
-- ---------------------------------------------------------
CREATE TABLE resena (
    id_resena BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_transaccion BIGINT NOT NULL
        REFERENCES transaccion(id_transaccion)
        ON DELETE RESTRICT,

    id_autor BIGINT NOT NULL
        REFERENCES usuario(id_usuario)
        ON DELETE RESTRICT,

    id_evaluado BIGINT NOT NULL
        REFERENCES usuario(id_usuario)
        ON DELETE RESTRICT,

    calificacion SMALLINT NOT NULL
        CHECK (calificacion BETWEEN 1 AND 5),

    comentario TEXT,

    fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_resena_transaccion_autor
        UNIQUE (id_transaccion, id_autor),

    CONSTRAINT chk_resena_participantes
        CHECK (id_autor <> id_evaluado)
);

CREATE INDEX idx_resena_evaluado
    ON resena (id_evaluado);

-- ---------------------------------------------------------
-- 11. CONVERSACIONES
-- ---------------------------------------------------------
CREATE TABLE conversacion (
    id_conversacion BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_publicacion BIGINT NOT NULL
        REFERENCES publicacion(id_publicacion)
        ON DELETE RESTRICT,

    id_interesado BIGINT NOT NULL
        REFERENCES usuario(id_usuario)
        ON DELETE RESTRICT,

    fecha_inicio TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_conversacion_publicacion_interesado
        UNIQUE (id_publicacion, id_interesado)
);

CREATE INDEX idx_conversacion_interesado
    ON conversacion (id_interesado);

-- ---------------------------------------------------------
-- 12. MENSAJES
-- ---------------------------------------------------------
CREATE TABLE mensaje (
    id_mensaje BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_conversacion BIGINT NOT NULL
        REFERENCES conversacion(id_conversacion)
        ON DELETE CASCADE,

    id_emisor BIGINT NOT NULL
        REFERENCES usuario(id_usuario)
        ON DELETE RESTRICT,

    contenido TEXT NOT NULL
        CHECK (LENGTH(TRIM(contenido)) > 0),

    fecha_envio TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    leido BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_mensaje_conversacion_fecha
    ON mensaje (id_conversacion, fecha_envio);

-- ---------------------------------------------------------
-- 13. PLANES PARA PUBLICACIONES DESTACADAS
-- ---------------------------------------------------------
CREATE TABLE plan_destacado (
    id_plan BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    nombre VARCHAR(100) NOT NULL UNIQUE,

    precio NUMERIC(10,2) NOT NULL
        CHECK (precio > 0),

    duracion_dias INTEGER NOT NULL
        CHECK (duracion_dias > 0),

    prioridad INTEGER NOT NULL DEFAULT 1
        CHECK (prioridad > 0),

    activo BOOLEAN NOT NULL DEFAULT TRUE
);

-- ---------------------------------------------------------
-- 14. PAGOS DE DESTACADOS
-- No almacenar números de tarjeta ni CVV.
-- ---------------------------------------------------------
CREATE TABLE pago (
    id_pago BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_usuario BIGINT NOT NULL
        REFERENCES usuario(id_usuario)
        ON DELETE RESTRICT,

    monto NUMERIC(10,2) NOT NULL
        CHECK (monto > 0),

    metodo VARCHAR(40) NOT NULL,

    referencia_pasarela VARCHAR(255),

    estado VARCHAR(15) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (
            estado IN (
                'PENDIENTE',
                'PAGADO',
                'FALLIDO',
                'REEMBOLSADO'
            )
        ),

    fecha_pago TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_pago_usuario_fecha
    ON pago (id_usuario, fecha_pago DESC);

CREATE UNIQUE INDEX uq_pago_referencia_pasarela
    ON pago (referencia_pasarela)
    WHERE referencia_pasarela IS NOT NULL;

-- ---------------------------------------------------------
-- 15. DESTACADOS
-- ---------------------------------------------------------
CREATE TABLE destacado (
    id_destacado BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_publicacion BIGINT NOT NULL
        REFERENCES publicacion(id_publicacion)
        ON DELETE RESTRICT,

    id_plan BIGINT NOT NULL
        REFERENCES plan_destacado(id_plan)
        ON DELETE RESTRICT,

    id_pago BIGINT UNIQUE
        REFERENCES pago(id_pago)
        ON DELETE RESTRICT,

    fecha_inicio TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_fin TIMESTAMPTZ NOT NULL,

    estado VARCHAR(15) NOT NULL DEFAULT 'ACTIVO'
        CHECK (estado IN ('ACTIVO', 'VENCIDO', 'CANCELADO')),

    CONSTRAINT chk_destacado_fechas
        CHECK (fecha_fin > fecha_inicio)
);

CREATE INDEX idx_destacado_publicacion_estado_fecha
    ON destacado (id_publicacion, estado, fecha_fin);

CREATE INDEX idx_destacado_vigencia
    ON destacado (estado, fecha_fin);

-- ---------------------------------------------------------
-- 16. REPORTES
-- ---------------------------------------------------------
CREATE TABLE reporte (
    id_reporte BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_reportante BIGINT NOT NULL
        REFERENCES usuario(id_usuario)
        ON DELETE RESTRICT,

    id_publicacion BIGINT NOT NULL
        REFERENCES publicacion(id_publicacion)
        ON DELETE RESTRICT,

    motivo VARCHAR(100) NOT NULL,
    descripcion TEXT,

    estado VARCHAR(15) NOT NULL DEFAULT 'ABIERTO'
        CHECK (estado IN ('ABIERTO', 'REVISADO', 'RESUELTO')),

    fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_reporte_estado_fecha
    ON reporte (estado, fecha DESC);

CREATE INDEX idx_reporte_publicacion
    ON reporte (id_publicacion);

